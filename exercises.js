/* ==========================================
   ЖЕКЕ ТАПСЫРМАНЫ ЭКРАНҒА ШЫҒАРУ
========================================== */

function loadIndividualExercise(sectionId, index) {

    const exerciseId = `${sectionId}_${index + 1}`;
    const exercise = individualExercises[exerciseId];

    const container = document.getElementById("exerciseContent");

    if (!container) return;

    if (!exercise) {
        container.innerHTML = `
            <h2>Тапсырма дайындалуда</h2>
            <p>Бұл тапсырманың жеке мазмұны келесі бөлімде енгізіледі.</p>
        `;
        return;
    }

    container.innerHTML = `
        <div class="individual-exercise">

            <div class="exercise-icon">
                ${exercise.icon}
            </div>

            <h2>${exercise.title}</h2>

            <div class="exercise-info-box">
                <h3>🎯 Мақсаты</h3>
                <p>${exercise.goal}</p>
            </div>

            <div class="exercise-info-box">
                <h3>📋 Орындау тәртібі</h3>
                <ol>
                    ${exercise.instructions.map(item => `
                        <li>${item}</li>
                    `).join("")}
                </ol>
            </div>

            <div class="exercise-info-box">
                <h3>⚠️ Ескерту</h3>
                <p>${exercise.warning}</p>
            </div>

            <div class="exercise-details">
                <p>⏱️ Ұзақтығы: ${exercise.duration}</p>
                <p>🔁 Қайталау: ${exercise.repetitions}</p>
                <p>🧰 Құралдар: ${exercise.equipment}</p>
            </div>

        </div>
    `;
}


/* ==========================================
   SCRIPT.JS ФАЙЛЫНА ҚОСЫЛУЫ ҮШІН
========================================== */

window.loadIndividualExercise = loadIndividualExercise;
